'use client';

import type { StudentMaterial } from '@/app/student/actions';
import { Icon } from '@/components/ui/icon';
import { Input } from '@/components/ui/input';
import { useRouter } from 'next/navigation';
import { useRef, useState, useEffect } from 'react';

export interface SearchBarProps {
  /** The value coming from `useSearch.inputValue` for pure typing state. */
  inputValue: string;
  /** Setter from `useSearch.setInputValue` that updates purely local input state. */
  setInputValue: (val: string) => void;
  /** The fully debounced query coming from `useSearch.debouncedQuery`. */
  debouncedQuery: string;
  /** The matching array from `useSearch.results`. (Only required if generating dropdowns). */
  results?: StudentMaterial[];
  placeholder?: string;
  /** Enables a Google-style floating panel of results overlaying the page context. */
  showDropdown?: boolean;
  /** Pass structural classes to the outermost div constraints. */
  className?: string;
}

/**
 * A highly reusable, unified component that standardizes search layout, clears state,
 * and seamlessly accepts values generated by `useSearch`. Supports optionally overlaying
 * its own Google-style floating suggestion boxes when `showDropdown` = true.
 */
export function SearchBar({
  inputValue,
  setInputValue,
  debouncedQuery,
  results = [],
  placeholder = 'Search documents, subjects, or types...',
  showDropdown = false,
  className = 'relative w-full max-w-md',
}: SearchBarProps) {
  const router = useRouter();

  // Floating dropdown state mechanics
  const [isFocused, setIsFocused] = useState(false);
  const dropdownRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (!showDropdown) return;

    const handleClickOutside = (event: MouseEvent) => {
      if (dropdownRef.current && !dropdownRef.current.contains(event.target as Node)) {
        setIsFocused(false);
      }
    };
    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, [showDropdown]);

  return (
    <div className={className} ref={dropdownRef}>
      <div className="relative">
        <Icon
          name="search"
          size="sm"
          className="text-muted-foreground pointer-events-none absolute top-1/2 left-3.5 -translate-y-1/2"
        />
        <Input
          placeholder={placeholder}
          value={inputValue}
          onChange={(e) => setInputValue(e.target.value)}
          onFocus={() => setIsFocused(true)}
          className="bg-background/80 focus-visible:ring-primary h-10 w-full pr-10 pl-10 text-sm font-medium shadow-sm backdrop-blur-md transition-opacity focus-visible:ring-2"
        />

        {inputValue && (
          <button
            type="button"
            onClick={() => setInputValue('')}
            className="text-muted-foreground hover:text-foreground absolute top-1/2 right-3 -translate-y-1/2"
            aria-label="Clear search"
          >
            <Icon name="close_small" size="xs" />
          </button>
        )}
      </div>

      {showDropdown && isFocused && inputValue && (
        <div className="bg-card border-border absolute top-full left-0 z-50 mt-2 w-full overflow-hidden rounded-xl border shadow-xl">
          <div className="max-h-72 overflow-y-auto p-2">
            {results.length > 0 ? (
              results.map((m: StudentMaterial) => (
                <button
                  key={m.id}
                  onClick={() => router.push(`/student/viewer/${m.id}`)}
                  className="hover:bg-accent flex w-full items-start gap-3 rounded-lg px-3 py-2 text-left transition-colors"
                >
                  <div className="bg-primary/10 flex h-10 w-10 shrink-0 items-center justify-center rounded-md">
                    <Icon name="book" size="sm" className="text-primary" />
                  </div>
                  <div className="flex w-full min-w-0 flex-col">
                    <span className="text-foreground truncate text-sm font-medium">{m.title}</span>
                    <span className="text-muted-foreground truncate text-xs">
                      {m.subject} · {m.materialType}
                    </span>
                  </div>
                </button>
              ))
            ) : (
              <div className="text-muted-foreground p-4 text-center text-sm">
                {debouncedQuery !== inputValue ? (
                  <span>Searching...</span>
                ) : (
                  <span>No materials found for &quot;{inputValue}&quot;.</span>
                )}
              </div>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
